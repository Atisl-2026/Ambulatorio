create or replace function private.norm(t text) returns text
language sql stable as $$ select lower(extensions.unaccent(coalesce(t, ''))) $$;

create or replace function public.archive_search(p jsonb) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  v_q text := private.norm(btrim(coalesce(p->>'q', '')));
  v_client text := private.norm(btrim(coalesce(p->>'client', '')));
  v_doctor bigint := nullif(p->>'doctor', '')::bigint;
  v_operator uuid := nullif(p->>'operator', '')::uuid;
  v_from date := nullif(p->>'from', '')::date;
  v_to date := nullif(p->>'to', '')::date;
  v_kind text := coalesce(p->>'kind', '');
  v_all jsonb;
begin
  perform private.require_user();
  with req as (
    select r.*, coalesce(r.date, r.created_at::date) as ref,
           (select string_agg(f.name, ' ') from public.files f where r.attachments ? f.id::text) as att
    from public.requests r where r.is_published
  ), app as (
    select a.*, d.name as doctor_name, d.specialty as doctor_specialty, o.display_name as operator_name
    from public.appointments a
    left join public.doctors d on d.id = a.doctor_id
    left join public.profiles o on o.id = a.operator_id
    where a.is_published
  ), res as (
    select 'request' as kind, r.id, r.ref as date, null::text as time, r.title, r.client, r.status as subtitle,
           r.created_by, r.updated_at, r.updated_by, r.locked, r.version
    from req r
    where v_kind <> 'appointment' and v_doctor is null
      and (v_from is null or r.ref >= v_from) and (v_to is null or r.ref <= v_to)
      and (v_client = '' or private.norm(r.client) like '%' || v_client || '%')
      and (v_operator is null or v_operator in (r.created_by, r.published_by, r.updated_by))
      and (v_q = '' or private.norm(concat_ws(' ', r.title, r.description, r.client, r.status, r.att)) like '%' || v_q || '%')
    union all
    select 'appointment', a.id, a.day, a.time, concat(a.client, ' — ', a.doctor_name), a.client,
           concat(a.time, ' · ', a.doctor_name, ' · operatrice ', a.operator_name, case when a.docs_checked then ' · documenti ✓' else '' end),
           a.created_by, a.updated_at, a.updated_by, a.locked, a.version
    from app a
    where v_kind <> 'request'
      and (v_from is null or a.day >= v_from) and (v_to is null or a.day <= v_to)
      and (v_client = '' or private.norm(a.client) like '%' || v_client || '%')
      and (v_doctor is null or a.doctor_id = v_doctor)
      and (v_operator is null or v_operator in (a.operator_id, a.created_by, a.published_by, a.updated_by))
      and (v_q = '' or private.norm(concat_ws(' ', a.client, a.notes, a.doctor_name, a.doctor_specialty, a.operator_name)) like '%' || v_q || '%')
  )
  select coalesce(jsonb_agg(jsonb_build_object(
      'kind', kind, 'id', id, 'date', date, 'time', time, 'title', title, 'client', client, 'subtitle', subtitle,
      'authorName', coalesce(private.user_name(created_by), '—'), 'updatedAt', updated_at,
      'updatedByName', coalesce(private.user_name(updated_by), '—'), 'locked', locked, 'version', version)
    order by date desc nulls last, time desc nulls last), '[]')
  into v_all from res;
  return jsonb_build_object('total', jsonb_array_length(v_all),
    'results', coalesce((select jsonb_agg(e) from (select e from jsonb_array_elements(v_all) e limit 500) s), '[]'));
end $$;

create or replace function public.archive_weeks() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare v jsonb;
begin
  perform private.require_user();
  with weeks as (
    select private.monday(day) as ws, count(*) as cnt, count(*) filter (where docs_checked) as docs,
           count(distinct doctor_id) as docs_n, max(updated_at) as last
    from public.appointments where is_published and day is not null group by 1
    union all
    select week_start, 0, 0, 0, null from public.week_locks
  ), agg as (
    select ws, sum(cnt) as cnt, sum(docs) as docs, max(docs_n) as docs_n, max(last) as last from weeks group by ws
  )
  select coalesce(jsonb_agg(jsonb_build_object(
      'weekStart', ws, 'weekKey', to_char(ws, 'IYYY-"W"IW'), 'count', cnt, 'docsChecked', docs, 'doctors', docs_n,
      'lastUpdate', last, 'locked', exists (select 1 from public.week_locks w where w.week_start = ws))
    order by ws desc), '[]') into v from agg;
  return v;
end $$;

create or replace function public.archive_week(p_week date) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare v_apps jsonb; v_hist jsonb;
begin
  perform private.require_user();
  select coalesce(jsonb_agg(private.with_names('appointment', private.row_data('appointment', to_jsonb(a)))
           || jsonb_build_object('id', a.id, 'locked', a.locked, 'updatedAt', a.updated_at,
                                 'updatedByName', coalesce(private.user_name(a.updated_by), '—'))
           order by a.day, a.time), '[]')
  into v_apps from public.appointments a where a.is_published and a.day between p_week and p_week + 5;
  select coalesce(jsonb_agg(to_jsonb(x) order by x.id desc), '[]') into v_hist from (
    select * from public.versions
    where (kind = 'appointment' and nullif(data->>'day', '') is not null and (data->>'day')::date between p_week and p_week + 5)
       or (kind = 'week' and item_id = to_char(p_week, 'YYYYMMDD')::bigint)
    order by id desc limit 500) x;
  return jsonb_build_object('weekStart', p_week, 'locked', private.week_locked(p_week), 'appointments', v_apps, 'history', v_hist);
end $$;

create or replace function public.delete_week(p_week date) returns jsonb
