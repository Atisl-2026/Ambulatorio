create or replace function public.set_week_lock(p_week date, p_locked boolean) returns jsonb
language plpgsql security definer set search_path = '' as $$
begin
  perform private.require_admin();
  if p_week is null or extract(isodow from p_week) <> 1 then perform private.fail(400, 'Settimana non valida.'); end if;
  if p_locked then
    insert into public.week_locks (week_start, locked_at, locked_by) values (p_week, now(), auth.uid())
    on conflict (week_start) do update set locked_at = now(), locked_by = auth.uid();
  else
    delete from public.week_locks where week_start = p_week;
  end if;
  perform private.add_version('week', to_char(p_week, 'YYYYMMDD')::bigint, 0,
    case when p_locked then 'Blocco settimana' else 'Sblocco settimana' end, jsonb_build_object('weekStart', p_week));
  perform private.log(case when p_locked then 'blocco_settimana' else 'sblocco_settimana' end,
    format('%s la settimana dal %s al %s', case when p_locked then 'Bloccata' else 'Sbloccata' end, p_week, p_week + 5), 'week', null);
  perform private.emit('week-lock', jsonb_build_object('weekStart', p_week, 'locked', p_locked));
  perform private.emit('appointments:changed', '{}');
  return jsonb_build_object('weekStart', p_week, 'locked', p_locked);
end $$;

