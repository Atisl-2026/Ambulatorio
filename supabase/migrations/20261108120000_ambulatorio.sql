create or replace function private.aset(p_key text, p_value text) returns void
language sql security definer set search_path = '' as $$
  insert into public.admin_settings (key, value, updated_at, updated_by) values (p_key, p_value, now(), auth.uid())
  on conflict (key) do update set value = excluded.value, updated_at = now(), updated_by = auth.uid();
$$;

create or replace function private.aget(p_key text) returns text
language sql stable security definer set search_path = '' as $$
  select value from public.admin_settings where key = p_key;
$$;

create or replace function private.previous_month() returns text
language sql stable as $$
  select to_char(date_trunc('month', (now() at time zone 'Europe/Rome')) - interval '1 day', 'YYYY-MM');
$$;

create or replace function public.get_mail_settings() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
begin
  perform private.require_admin();
  return jsonb_build_object(
    'enabled', coalesce(private.aget('monthly_email_enabled'), '0') = '1',
    'recipients', coalesce(private.aget('monthly_email_to'), ''),
    'lastMonth', private.aget('monthly_email_last_month'),
    'lastSentAt', private.aget('monthly_email_last_sent_at'),
    'lastError', nullif(private.aget('monthly_email_last_error'), ''),
    'nextMonth', to_char((now() at time zone 'Europe/Rome'), 'YYYY-MM'),
    'functionsUrl', private.aget('functions_url'));
end $$;

create or replace function public.set_mail_settings(p_enabled boolean, p_recipients text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare v_list text[]; e text; v_was boolean;
begin
  perform private.require_admin();
  select coalesce(array_agg(x), '{}') into v_list
  from (select btrim(x) as x from regexp_split_to_table(coalesce(p_recipients, ''), '[,;\s]+') x) s where x <> '';
  if cardinality(v_list) > 5 then perform private.fail(400, 'Al massimo 5 indirizzi email.'); end if;
  foreach e in array v_list loop
    if e !~ '^[^\s@,;]+@[^\s@,;]+\.[^\s@,;]+$' or length(e) > 200 then
      perform private.fail(400, 'Indirizzo email non valido: ' || e);
    end if;
  end loop;
  if p_enabled and cardinality(v_list) = 0 then perform private.fail(400, 'Inserisci almeno un indirizzo email.'); end if;
  v_was := coalesce(private.aget('monthly_email_enabled'), '0') = '1';
  perform private.aset('monthly_email_to', array_to_string(v_list, ', '));
  perform private.aset('monthly_email_enabled', case when p_enabled then '1' else '0' end);
  -- All'attivazione il mese già concluso non parte subito: il primo invio sarà il prossimo 1° del mese.
  if p_enabled and not v_was then perform private.aset('monthly_email_last_month', private.previous_month()); end if;
  perform private.log('impostazioni', format('Invio mensile del calendario %s',
    case when p_enabled then 'ATTIVO verso ' || array_to_string(v_list, ', ') else 'disattivato' end));
  return public.get_mail_settings();
end $$;

-- L'app del Capo comunica l'indirizzo delle funzioni, usato dal pianificatore orario.
create or replace function public.register_functions_url(p_url text) returns void
language plpgsql security definer set search_path = '' as $$
begin
  perform private.require_admin();
  if p_url !~ '^https?://[^\s]+/functions/v1$' then perform private.fail(400, 'Indirizzo non valido.'); end if;
  if private.aget('functions_url') is distinct from p_url then perform private.aset('functions_url', p_url); end if;
end $$;

-- Ogni ora il database "sveglia" la funzione di invio, che decide se è il momento di spedire.
create or replace function private.cron_monthly_email() returns void
language plpgsql security definer set search_path = '' as $$
declare v_url text := private.aget('functions_url');
begin
  if v_url is null or coalesce(private.aget('monthly_email_enabled'), '0') <> '1' then return; end if;
  perform net.http_post(
    url := v_url || '/monthly-email',
    body := jsonb_build_object('mode', 'cron'),
    headers := jsonb_build_object('Content-Type', 'application/json', 'x-cron-secret', private.aget('cron_secret')));
end $$;

select cron.schedule('ambulatorio-email-mensile', '7 * * * *', 'select private.cron_monthly_email()');
select cron.schedule('ambulatorio-pulizia-eventi', '17 3 * * *', $$delete from public.events where at < now() - interval '2 days'$$);

