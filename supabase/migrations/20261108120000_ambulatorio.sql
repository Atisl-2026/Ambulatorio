create or replace function private.fail(p_status int, p_message text) returns void
language plpgsql as $$
begin
  -- PostgREST trasforma SQLSTATE 'PTnnn' nel codice HTTP nnn.
  raise exception using errcode = 'PT' || p_status::text, message = p_message;
end $$;

create or replace function private.uid_ok() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.profiles p
                 where p.id = auth.uid() and p.active and not p.must_change_password);
$$;

create or replace function private.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.profiles p
                 where p.id = auth.uid() and p.active and not p.must_change_password and p.role = 'admin');
$$;

create or replace function private.is_service() returns boolean
language sql stable as $$
  select coalesce(current_setting('request.jwt.claims', true)::jsonb ->> 'role', '') = 'service_role';
$$;

create or replace function private.require_user() returns void
language plpgsql stable security definer set search_path = '' as $$
declare p public.profiles;
begin
  select * into p from public.profiles where id = auth.uid();
  if p.id is null or not p.active then
    perform private.fail(401, 'Sessione scaduta o non valida. Effettua di nuovo l''accesso.');
  end if;
  if p.must_change_password then
    perform private.fail(403, 'Devi cambiare la password prima di continuare.');
  end if;
end $$;

create or replace function private.require_admin() returns void
language plpgsql stable security definer set search_path = '' as $$
begin
  if private.is_service() then return; end if;
  perform private.require_user();
  if not private.is_admin() then
    perform private.fail(403, 'Funzione riservata all''amministratore.');
  end if;
end $$;

create or replace function private.user_name(p uuid) returns text
language sql stable security definer set search_path = '' as $$
  select display_name from public.profiles where id = p;
$$;

create or replace function private.monday(d date) returns date
language sql immutable as $$ select d - (extract(isodow from d)::int - 1) $$;

create or replace function private.week_locked(d date) returns boolean
language sql stable security definer set search_path = '' as $$
  select d is not null and exists (select 1 from public.week_locks w where w.week_start = private.monday(d));
$$;

create or replace function private.emit(p_type text, p_payload jsonb default '{}', p_target uuid default null) returns void
language sql security definer set search_path = '' as $$
  insert into public.events (type, payload, target) values (p_type, coalesce(p_payload, '{}'), p_target);
$$;

create or replace function private.log(p_action text, p_details text, p_kind text default null, p_item bigint default null) returns void
language sql security definer set search_path = '' as $$
  insert into public.activity_log (user_id, user_name, action, kind, item_id, details)
  values (auth.uid(),
          coalesce(private.user_name(auth.uid()), case when private.is_service() then 'Sistema' end),
          p_action, p_kind, p_item, p_details);
$$;

create or replace function private.str(v text, maxlen int, field text) returns text
language plpgsql immutable as $$
declare s text := btrim(coalesce(v, ''));
begin
  if length(s) > maxlen then
    perform private.fail(400, format('Il campo "%s" supera i %s caratteri.', field, maxlen));
  end if;
  return s;
end $$;

create or replace function private.parse_date(v text, msg text) returns date
language plpgsql immutable as $$
declare d date;
begin
  if v is null or v = '' then return null; end if;
  if v !~ '^\d{4}-\d{2}-\d{2}$' then perform private.fail(400, msg); end if;
  begin
    d := v::date;
  exception when others then
    perform private.fail(400, msg);
  end;
  if to_char(d, 'YYYY-MM-DD') <> v then perform private.fail(400, msg); end if;
  return d;
end $$;

create or replace function private.event_for(p_kind text) returns text
language sql immutable as $$
  select case p_kind when 'request' then 'requests:changed' else 'appointments:changed' end;
$$;

create or replace function private.label(p_kind text) returns text
language sql immutable as $$ select case p_kind when 'request' then 'richiesta' else 'appuntamento' end $$;

create or replace function private.describe(p_kind text, d jsonb) returns text
language sql immutable as $$
  select case p_kind
    when 'request' then format('"%s"', coalesce(nullif(d->>'title', ''), 'senza titolo'))
    else btrim(format('%s %s %s', coalesce(nullif(d->>'client', ''), 'senza cliente'), coalesce(d->>'day', ''), coalesce(d->>'time', '')))
  end;
$$;

-- Normalizza e valida i dati in ingresso (stesse regole per bozze e pubblicazione).
create or replace function private.sanitize(p_kind text, p jsonb) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  v_status text;
  v_att jsonb := '[]';
  v_id text;
  v_date date;
  v_op uuid;
  v_doc bigint;
  v_time text;
begin
  p := coalesce(p, '{}');
  if p_kind = 'request' then
    v_date := private.parse_date(nullif(p->>'date', ''), 'Data non valida.');
    v_status := coalesce(nullif(p->>'status', ''), 'Nuova');
    if v_status not in ('Nuova', 'In lavorazione', 'In attesa', 'Completata', 'Annullata') then
      perform private.fail(400, 'Stato non valido.');
    end if;
    if jsonb_typeof(p->'attachments') = 'array' then
      for v_id in
        select distinct on (x) x from (
          select coalesce(e->>'id', e #>> '{}') as x, ord
          from jsonb_array_elements(p->'attachments') with ordinality as t(e, ord)
        ) s order by x
      loop
        if not exists (select 1 from public.files f where f.id::text = v_id) then
          perform private.fail(400, 'Allegato non trovato.');
        end if;
        v_att := v_att || to_jsonb(v_id);
      end loop;
      if jsonb_array_length(v_att) > 30 then perform private.fail(400, 'Massimo 30 allegati.'); end if;
    end if;
    return jsonb_build_object(
      'title', private.str(p->>'title', 200, 'Titolo'),
      'description', private.str(p->>'description', 20000, 'Descrizione'),
      'client', private.str(p->>'client', 200, 'Cliente'),
      'date', coalesce(to_char(v_date, 'YYYY-MM-DD'), ''),
      'status', v_status,
      'attachments', v_att);
  end if;

  if nullif(p->>'operator_id', '') is not null then
    begin
      v_op := (p->>'operator_id')::uuid;
    exception when others then
      perform private.fail(400, 'Operatrice non valida.');
    end;
    if not exists (select 1 from public.profiles where id = v_op) then perform private.fail(400, 'Operatrice non valida.'); end if;
  end if;
  if nullif(p->>'doctor_id', '') is not null then
    begin
      v_doc := (p->>'doctor_id')::bigint;
    exception when others then
      perform private.fail(400, 'Medico non valido.');
    end;
    if not exists (select 1 from public.doctors where id = v_doc) then perform private.fail(400, 'Medico non valido.'); end if;
  end if;
  v_date := private.parse_date(nullif(p->>'day', ''), 'Giorno non valido.');
  if v_date is not null and extract(isodow from v_date) = 7 then
    perform private.fail(400, 'L''ambulatorio è aperto dal lunedì al sabato.');
  end if;
  v_time := nullif(p->>'time', '');
  if v_time is not null and v_time !~ '^([01]\d|2[0-3]):[0-5]\d$' then
    perform private.fail(400, 'Orario non valido (formato HH:MM).');
  end if;
  return jsonb_build_object(
    'operator_id', v_op,
    'doctor_id', v_doc,
    'day', coalesce(to_char(v_date, 'YYYY-MM-DD'), ''),
    'time', coalesce(v_time, ''),
    'client', private.str(p->>'client', 200, 'Cliente'),
    'docs_checked', coalesce((p->>'docs_checked')::boolean, false),
    'notes', private.str(p->>'notes', 5000, 'Note'));
end $$;

create or replace function private.validate_publish(p_kind text, d jsonb) returns void
language plpgsql immutable as $$
declare missing text[] := '{}';
begin
  if p_kind = 'request' then
    if d->>'title' = '' then perform private.fail(400, 'Il titolo è obbligatorio per pubblicare.'); end if;
    if d->>'client' = '' then perform private.fail(400, 'Il cliente è obbligatorio per pubblicare.'); end if;
    if d->>'date' = '' then perform private.fail(400, 'La data è obbligatoria per pubblicare.'); end if;
    return;
  end if;
  if d->>'operator_id' is null then missing := array_append(missing, 'operatrice'); end if;
  if d->>'doctor_id' is null then missing := array_append(missing, 'medico'); end if;
  if d->>'day' = '' then missing := array_append(missing, 'giorno'); end if;
  if d->>'time' = '' then missing := array_append(missing, 'orario'); end if;
  if d->>'client' = '' then missing := array_append(missing, 'cliente'); end if;
  if cardinality(missing) > 0 then
    perform private.fail(400, 'Per pubblicare compila: ' || array_to_string(missing, ', ') || '.');
  end if;
end $$;

-- Dati "di contenuto" di una riga (stessa forma della bozza).
create or replace function private.row_data(p_kind text, r jsonb) returns jsonb
language sql immutable as $$
  select case p_kind
    when 'request' then jsonb_build_object(
      'title', r->>'title', 'description', r->>'description', 'client', r->>'client',
      'date', coalesce(r->>'date', ''), 'status', r->>'status', 'attachments', coalesce(r->'attachments', '[]'))
    else jsonb_build_object(
      'operator_id', r->'operator_id', 'doctor_id', r->'doctor_id', 'day', coalesce(r->>'day', ''),
      'time', coalesce(r->>'time', ''), 'client', r->>'client', 'docs_checked', coalesce((r->>'docs_checked')::boolean, false),
      'notes', r->>'notes')
  end;
$$;

create or replace function private.with_names(p_kind text, d jsonb, p_short boolean default false) returns jsonb
language sql stable security definer set search_path = '' as $$
  select case p_kind
    when 'request' then d || jsonb_build_object('attachments', coalesce((
      select jsonb_agg(case when p_short then jsonb_build_object('id', f.id, 'name', f.name)
                            else jsonb_build_object('id', f.id, 'name', f.name, 'mime', f.mime, 'size', f.size, 'path', f.path) end
                       order by a.ord)
      from jsonb_array_elements_text(coalesce(d->'attachments', '[]')) with ordinality as a(fid, ord)
      join public.files f on f.id::text = a.fid), '[]'::jsonb))
    else d || jsonb_build_object(
      'operator_name', coalesce((select display_name from public.profiles where id::text = d->>'operator_id'), ''),
      'doctor_name', coalesce((select name from public.doctors where id::text = d->>'doctor_id'), ''),
      'doctor_specialty', coalesce((select specialty from public.doctors where id::text = d->>'doctor_id'), ''))
  end;
$$;

create or replace function private.serialize(p_kind text, r jsonb, d public.drafts) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  v_pub boolean := (r->>'is_published')::boolean;
  v_draft jsonb := null;
  v_out jsonb;
begin
  if d.id is not null then
    v_draft := private.with_names(p_kind, d.data) || jsonb_build_object(
      'updatedAt', d.updated_at, 'baseVersion', d.base_version,
      'stale', v_pub and d.base_version < (r->>'version')::int);
  end if;
  v_out := jsonb_build_object(
    'kind', p_kind,
    'id', (r->>'id')::bigint,
    'isPublished', v_pub,
    'version', (r->>'version')::int,
    'published', case when v_pub then private.with_names(p_kind, private.row_data(p_kind, r)) end,
    'draft', v_draft,
    'locked', (r->>'locked')::boolean,
    'lockedAt', r->'locked_at',
    'lockedByName', private.user_name((r->>'locked_by')::uuid),
    'authorName', private.user_name((r->>'created_by')::uuid),
    'createdAt', r->'created_at',
    'updatedAt', r->'updated_at',
    'updatedByName', private.user_name((r->>'updated_by')::uuid),
    'publishedAt', r->'published_at',
    'publishedByName', private.user_name((r->>'published_by')::uuid));
  if p_kind = 'appointment' then
    v_out := v_out || jsonb_build_object(
      'weekLocked', v_pub and private.week_locked(nullif(r->>'day', '')::date),
      'draftWeekLocked', v_draft is not null and private.week_locked(nullif(v_draft->>'day', '')::date));
  end if;
  return v_out;
end $$;

create or replace function private.load_row(p_kind text, p_id bigint) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare r jsonb;
begin
  if p_kind = 'request' then
    select to_jsonb(t) into r from public.requests t where t.id = p_id;
  elsif p_kind = 'appointment' then
    select to_jsonb(t) into r from public.appointments t where t.id = p_id;
  else
    perform private.fail(404, 'Tipo non valido.');
  end if;
  if r is null then perform private.fail(404, 'Elemento non trovato (potrebbe essere stato eliminato).'); end if;
  return r;
end $$;

create or replace function private.my_draft(p_kind text, p_id bigint) returns public.drafts
language sql stable security definer set search_path = '' as $$
  select * from public.drafts where kind = p_kind and item_id = p_id and user_id = auth.uid();
$$;

create or replace function private.assert_editable(p_kind text, r jsonb, p_new jsonb) returns void
language plpgsql stable security definer set search_path = '' as $$
begin
  if private.is_admin() then return; end if;
  if r is not null and (r->>'locked')::boolean then perform private.fail(423, 'BLOCCATO DAL CAPO'); end if;
  if p_kind = 'appointment' then
    if r is not null and (r->>'is_published')::boolean and private.week_locked(nullif(r->>'day', '')::date) then
      perform private.fail(423, 'BLOCCATO DAL CAPO');
    end if;
    if p_new is not null and private.week_locked(nullif(p_new->>'day', '')::date) then
      perform private.fail(423, 'BLOCCATO DAL CAPO');
    end if;
  end if;
end $$;

create or replace function private.add_version(p_kind text, p_item bigint, p_version int, p_action text, p_data jsonb) returns void
language sql security definer set search_path = '' as $$
  insert into public.versions (kind, item_id, version, action, data, user_id, user_name)
  values (p_kind, p_item, p_version, p_action, p_data, auth.uid(), private.user_name(auth.uid()));
$$;

-- Accesso agli allegati (usato anche dalle regole dello Storage).
create or replace function private.can_read_file(p_path text) returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (
    select 1 from public.files f
    where f.path = p_path and (
      private.is_admin()
      or f.uploaded_by = auth.uid()
      or exists (select 1 from public.requests r where r.is_published and r.attachments ? f.id::text)
      or exists (select 1 from public.drafts d where d.kind = 'request' and d.user_id = auth.uid() and d.data->'attachments' ? f.id::text)
    ));
$$;

