create or replace function public.save_doctor(p_id bigint, p_name text default null, p_specialty text default null, p_active boolean default null) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare v_id bigint := p_id; v_name text; v_spec text; v_old public.doctors;
begin
  perform private.require_admin();
  if v_id is not null then
    select * into v_old from public.doctors where id = v_id;
    if v_old.id is null then perform private.fail(404, 'Medico non trovato.'); end if;
  end if;
  -- Valori non indicati (null) restano invariati.
  v_name := private.str(coalesce(p_name, v_old.name), 120, 'Nome medico');
  v_spec := private.str(coalesce(p_specialty, v_old.specialty), 120, 'Specialità');
  if v_name = '' then perform private.fail(400, 'Il nome del medico è obbligatorio.'); end if;
  if v_id is null then
    insert into public.doctors (name, specialty, active, created_by, updated_by)
    values (v_name, v_spec, true, auth.uid(), auth.uid()) returning id into v_id;
    perform private.log('medico_creato', format('Aggiunto medico %s%s', v_name, case when v_spec <> '' then ' (' || v_spec || ')' else '' end), 'doctor', v_id);
  else
    update public.doctors set name = v_name, specialty = v_spec, active = coalesce(p_active, active),
      updated_at = now(), updated_by = auth.uid() where id = v_id;
    perform private.log('medico_modificato', format('Medico %s aggiornato%s', v_old.name,
      case when coalesce(p_active, v_old.active) <> v_old.active then case when p_active then ' (riattivato)' else ' (disattivato)' end else '' end), 'doctor', v_id);
  end if;
  perform private.emit('doctors:changed', '{}');
  return jsonb_build_object('id', v_id);
end $$;

