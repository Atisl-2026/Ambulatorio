-- Gli account (utenti e password) non si ripristinano: restano quelli attuali.
create or replace function public.backup_restore(p jsonb) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare t jsonb := p->'tables'; v_me uuid := auth.uid(); v_name text := private.user_name(auth.uid());
begin
  perform private.require_admin();
  if p->>'app' <> 'ambulatorio' or t is null then perform private.fail(400, 'Il file non è un backup di questa applicazione.'); end if;
  -- "where true": le API di Supabase vietano DELETE senza condizione.
  delete from public.drafts where true; delete from public.versions where true; delete from public.week_locks where true;
  delete from public.requests where true; delete from public.appointments where true; delete from public.doctors where true;
  delete from public.files where true; delete from public.activity_log where true; delete from public.settings where true;
  delete from public.admin_settings where key not in ('cron_secret', 'functions_url');
  insert into public.settings select * from jsonb_populate_recordset(null::public.settings, t->'settings');
  insert into public.admin_settings select * from jsonb_populate_recordset(null::public.admin_settings, t->'admin_settings')
    on conflict (key) do nothing;
  insert into public.doctors overriding system value select * from jsonb_populate_recordset(null::public.doctors, t->'doctors');
  insert into public.requests overriding system value select * from jsonb_populate_recordset(null::public.requests, t->'requests');
  insert into public.appointments overriding system value select * from jsonb_populate_recordset(null::public.appointments, t->'appointments');
  insert into public.drafts overriding system value select * from jsonb_populate_recordset(null::public.drafts, t->'drafts');
  insert into public.week_locks select * from jsonb_populate_recordset(null::public.week_locks, t->'week_locks');
  insert into public.versions overriding system value select * from jsonb_populate_recordset(null::public.versions, t->'versions');
  insert into public.files select * from jsonb_populate_recordset(null::public.files, t->'files');
  insert into public.activity_log overriding system value select * from jsonb_populate_recordset(null::public.activity_log, t->'activity_log');
  -- Riallinea i contatori automatici.
  perform setval(pg_get_serial_sequence('public.doctors', 'id'), greatest((select max(id) from public.doctors), 1));
  perform setval(pg_get_serial_sequence('public.requests', 'id'), greatest((select max(id) from public.requests), 1));
  perform setval(pg_get_serial_sequence('public.appointments', 'id'), greatest((select max(id) from public.appointments), 1));
  perform setval(pg_get_serial_sequence('public.drafts', 'id'), greatest((select max(id) from public.drafts), 1));
  perform setval(pg_get_serial_sequence('public.versions', 'id'), greatest((select max(id) from public.versions), 1));
  perform setval(pg_get_serial_sequence('public.activity_log', 'id'), greatest((select max(id) from public.activity_log), 1));
  insert into public.activity_log (user_id, user_name, action, details)
  values (v_me, v_name, 'ripristino', format('Archivio ripristinato dal backup del %s', to_char((p->>'createdAt')::timestamptz at time zone 'Europe/Rome', 'DD/MM/YYYY HH24:MI')));
  perform private.emit('resync', '{}');
  return jsonb_build_object('ok', true);
end $$;

