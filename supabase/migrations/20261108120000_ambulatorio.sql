  v_action text := nullif(p->>'action', '');
  v_q text := nullif(p->>'q', '');
  v_from date := nullif(p->>'from', '')::date;
  v_to date := nullif(p->>'to', '')::date;
  v_limit int := least(coalesce((p->>'limit')::int, 50), 200);
  v_offset int := greatest(coalesce((p->>'offset')::int, 0), 0);
  v_total int; v_rows jsonb; v_actions jsonb;
begin
  perform private.require_admin();
  select count(*) into v_total from public.activity_log l
  where (v_user is null or l.user_id = v_user) and (v_action is null or l.action = v_action)
    and (v_q is null or l.details ilike '%' || v_q || '%')
    and (v_from is null or l.at >= v_from) and (v_to is null or l.at < v_to + 1);
  select coalesce(jsonb_agg(to_jsonb(x) order by x.id desc), '[]') into v_rows from (
    select l.* from public.activity_log l
    where (v_user is null or l.user_id = v_user) and (v_action is null or l.action = v_action)
      and (v_q is null or l.details ilike '%' || v_q || '%')
      and (v_from is null or l.at >= v_from) and (v_to is null or l.at < v_to + 1)
    order by l.id desc limit v_limit offset v_offset) x;
  select coalesce(jsonb_agg(a order by a), '[]') into v_actions from (select distinct action as a from public.activity_log) s;
  return jsonb_build_object('total', v_total, 'rows', v_rows, 'actions', v_actions);
end $$;

-- Righe del calendario per l'Excel (solo Capo o funzione di sistema).
create or replace function public.export_rows(p_from date, p_to date) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare v jsonb;
begin
  perform private.require_admin();
  select coalesce(jsonb_agg(jsonb_build_object(
      'operator', coalesce(o.display_name, ''), 'doctor', coalesce(d.name, ''), 'specialty', coalesce(d.specialty, ''),
      'day', a.day, 'time', a.time, 'client', a.client, 'docs', a.docs_checked, 'notes', a.notes,
      'locked', a.locked, 'weekLocked', private.week_locked(a.day),
      'updatedBy', coalesce(private.user_name(a.updated_by), ''), 'updatedAt', a.updated_at)
    order by a.day, a.time, a.id), '[]') into v
  from public.appointments a
  left join public.profiles o on o.id = a.operator_id
  left join public.doctors d on d.id = a.doctor_id
  where a.is_published and a.day between p_from and p_to;
  return v;
end $$;

