create or replace function public.list_items(p_kind text, p_from date default null, p_to date default null) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare v jsonb;
begin
  perform private.require_user();
  if p_kind = 'request' then
    select coalesce(jsonb_agg(private.serialize('request', to_jsonb(r), d) order by r.id), '[]') into v
    from public.requests r
    left join public.drafts d on d.kind = 'request' and d.item_id = r.id and d.user_id = auth.uid()
    where r.is_published or d.id is not null;
  elsif p_kind = 'appointment' then
    if p_from is null or p_to is null then perform private.fail(400, 'Intervallo date non valido.'); end if;
    select coalesce(jsonb_agg(private.serialize('appointment', to_jsonb(r), d) order by r.day, r.time, r.id), '[]') into v
    from public.appointments r
    left join public.drafts d on d.kind = 'appointment' and d.item_id = r.id and d.user_id = auth.uid()
    where (r.is_published and r.day between p_from and p_to)
       or (d.id is not null and (
            (nullif(d.data->>'day', '') is not null and (d.data->>'day')::date between p_from and p_to)
            or (nullif(d.data->>'day', '') is null and not r.is_published)));
  else
    perform private.fail(404, 'Tipo non valido.');
  end if;
  return v;
end $$;

create or replace function public.get_item(p_kind text, p_id bigint) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare r jsonb; d public.drafts;
begin
  perform private.require_user();
  r := private.load_row(p_kind, p_id);
  d := private.my_draft(p_kind, p_id);
  if not (r->>'is_published')::boolean and d.id is null then
    perform private.fail(404, 'Elemento non trovato.');
  end if;
  return private.serialize(p_kind, r, d);
end $$;

create or replace function public.create_item(p_kind text, p_data jsonb) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare v jsonb; v_id bigint;
begin
  perform private.require_user();
  v := private.sanitize(p_kind, p_data);
  perform private.assert_editable(p_kind, null, v);
  if p_kind = 'request' then
    insert into public.requests (created_by, updated_by) values (auth.uid(), auth.uid()) returning id into v_id;
  else
    insert into public.appointments (created_by, updated_by) values (auth.uid(), auth.uid()) returning id into v_id;
  end if;
  insert into public.drafts (kind, item_id, user_id, data, base_version) values (p_kind, v_id, auth.uid(), v, 0);
  perform private.log('bozza_creata', format('Nuova bozza di %s %s', private.label(p_kind), private.describe(p_kind, v)), p_kind, v_id);
  perform private.emit(private.event_for(p_kind), jsonb_build_object('id', v_id, 'draft', true), auth.uid());
  return public.get_item(p_kind, v_id);
end $$;

create or replace function public.save_draft(p_kind text, p_id bigint, p_data jsonb) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare r jsonb; d public.drafts; v jsonb;
begin
  perform private.require_user();
  r := private.load_row(p_kind, p_id);
  d := private.my_draft(p_kind, p_id);
  if not (r->>'is_published')::boolean and d.id is null then perform private.fail(404, 'Elemento non trovato.'); end if;
  v := private.sanitize(p_kind, p_data);
  perform private.assert_editable(p_kind, r, v);
  insert into public.drafts (kind, item_id, user_id, data, base_version)
  values (p_kind, p_id, auth.uid(), v, (r->>'version')::int)
  on conflict (kind, item_id, user_id) do update set data = excluded.data, updated_at = now();
  perform private.log('bozza_salvata', format('Bozza salvata: %s %s', private.label(p_kind), private.describe(p_kind, v)), p_kind, p_id);
  perform private.emit(private.event_for(p_kind), jsonb_build_object('id', p_id, 'draft', true), auth.uid());
  return public.get_item(p_kind, p_id);
end $$;

create or replace function public.discard_draft(p_kind text, p_id bigint) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare r jsonb; d public.drafts; v_deleted boolean := false;
begin
  perform private.require_user();
  r := private.load_row(p_kind, p_id);
  d := private.my_draft(p_kind, p_id);
  if d.id is null then perform private.fail(404, 'Nessuna bozza da annullare.'); end if;
  delete from public.drafts where id = d.id;
  if not (r->>'is_published')::boolean
     and not exists (select 1 from public.drafts where kind = p_kind and item_id = p_id) then
    if p_kind = 'request' then delete from public.requests where id = p_id;
    else delete from public.appointments where id = p_id; end if;
    v_deleted := true;
  end if;
  perform private.log('bozza_annullata', format('Bozza annullata: %s %s', private.label(p_kind), private.describe(p_kind, d.data)), p_kind, p_id);
  perform private.emit(private.event_for(p_kind), jsonb_build_object('id', p_id, 'draft', true), auth.uid());
  return jsonb_build_object('ok', true, 'deleted', v_deleted);
end $$;

create or replace function public.publish_item(p_kind text, p_id bigint, p_data jsonb default null) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare r jsonb := null; d public.drafts; v jsonb; v_first boolean; v_version int; v_id bigint := p_id;
begin
  perform private.require_user();
  if p_id is not null then
    r := private.load_row(p_kind, p_id);
    d := private.my_draft(p_kind, p_id);
    if d.id is null and p_data is null then perform private.fail(400, 'Non ci sono modifiche da pubblicare.'); end if;
    if not (r->>'is_published')::boolean and d.id is null then perform private.fail(404, 'Elemento non trovato.'); end if;
  end if;
  v := private.sanitize(p_kind, coalesce(p_data, d.data));
  perform private.assert_editable(p_kind, r, v);
  perform private.validate_publish(p_kind, v);
  v_first := r is null or not (r->>'is_published')::boolean;
  v_version := coalesce((r->>'version')::int, 0) + 1;

  if p_kind = 'request' then
    if v_id is null then
      insert into public.requests (created_by, updated_by) values (auth.uid(), auth.uid()) returning id into v_id;
    end if;
    update public.requests set
      title = v->>'title', description = v->>'description', client = v->>'client',
      date = nullif(v->>'date', '')::date, status = v->>'status', attachments = v->'attachments',
      is_published = true, version = v_version, published_at = now(), published_by = auth.uid(),
      updated_at = now(), updated_by = auth.uid()
    where id = v_id;
  else
    if v_id is null then
      insert into public.appointments (created_by, updated_by) values (auth.uid(), auth.uid()) returning id into v_id;
    end if;
    update public.appointments set
      operator_id = (v->>'operator_id')::uuid, doctor_id = (v->>'doctor_id')::bigint,
      day = nullif(v->>'day', '')::date, time = v->>'time', client = v->>'client',
      docs_checked = (v->>'docs_checked')::boolean, notes = v->>'notes',
      is_published = true, version = v_version, published_at = now(), published_by = auth.uid(),
      updated_at = now(), updated_by = auth.uid()
    where id = v_id;
  end if;
  delete from public.drafts where kind = p_kind and item_id = v_id and user_id = auth.uid();
  perform private.add_version(p_kind, v_id, v_version, case when v_first then 'Creazione' else 'Modifica' end,
                              private.with_names(p_kind, v, true));
  perform private.log('pubblicazione',
    format('%s %s %s', case when v_first then 'Pubblicata nuova' else 'Pubblicata modifica di' end, private.label(p_kind), private.describe(p_kind, v)),
    p_kind, v_id);
  perform private.emit(private.event_for(p_kind), jsonb_build_object('id', v_id));
  return public.get_item(p_kind, v_id);
end $$;

create or replace function public.set_item_lock(p_kind text, p_id bigint, p_locked boolean) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare r jsonb; v jsonb;
begin
  perform private.require_admin();
  r := private.load_row(p_kind, p_id);
  if not (r->>'is_published')::boolean then perform private.fail(400, 'Si possono bloccare solo elementi pubblicati.'); end if;
  if p_kind = 'request' then
    update public.requests set locked = p_locked, locked_at = case when p_locked then now() end,
      locked_by = case when p_locked then auth.uid() end, updated_at = now(), updated_by = auth.uid() where id = p_id;
  else
    update public.appointments set locked = p_locked, locked_at = case when p_locked then now() end,
      locked_by = case when p_locked then auth.uid() end, updated_at = now(), updated_by = auth.uid() where id = p_id;
  end if;
  v := private.row_data(p_kind, r);
  perform private.add_version(p_kind, p_id, (r->>'version')::int, case when p_locked then 'Blocco' else 'Sblocco' end,
                              private.with_names(p_kind, v, true));
  perform private.log(case when p_locked then 'blocco' else 'sblocco' end,
    format('%s: %s %s', case when p_locked then 'Bloccato' else 'Sbloccato' end, private.label(p_kind), private.describe(p_kind, v)), p_kind, p_id);
  perform private.emit('lock', jsonb_build_object('kind', p_kind, 'id', p_id, 'locked', p_locked));
  perform private.emit(private.event_for(p_kind), jsonb_build_object('id', p_id));
  return public.get_item(p_kind, p_id);
end $$;

create or replace function public.delete_item(p_kind text, p_id bigint) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare r jsonb; v_paths jsonb := '[]';
begin
  perform private.require_admin();
  r := private.load_row(p_kind, p_id);
  if p_kind = 'request' then
    delete from public.requests where id = p_id;
    -- Allegati non più usati da nessuno: tolti dall'elenco, il client elimina i file dallo Storage.
    with gone as (
      delete from public.files f
      where (r->'attachments') ? f.id::text
        and not exists (select 1 from public.requests q where q.attachments ? f.id::text)
        and not exists (select 1 from public.drafts dd where dd.kind = 'request' and dd.data->'attachments' ? f.id::text)
      returning f.path)
    select coalesce(jsonb_agg(path), '[]') into v_paths from gone;
  else
    delete from public.appointments where id = p_id;
  end if;
  delete from public.drafts where kind = p_kind and item_id = p_id;
  delete from public.versions where kind = p_kind and item_id = p_id;
  perform private.log('eliminazione', format('Eliminato definitivamente: %s %s', private.label(p_kind), private.describe(p_kind, private.row_data(p_kind, r))), p_kind, p_id);
  perform private.emit('deleted', jsonb_build_object('kind', p_kind, 'id', p_id));
  perform private.emit(private.event_for(p_kind), jsonb_build_object('id', p_id));
  return jsonb_build_object('ok', true, 'paths', v_paths);
end $$;

create or replace function public.list_versions(p_kind text, p_id bigint) returns jsonb
